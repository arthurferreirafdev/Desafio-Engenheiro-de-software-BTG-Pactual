-- Schema conforme o DER (doc/DER.drawio), com ajustes operacionais documentados no relatório.

CREATE TABLE produto (
    codigo_produto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(200) NOT NULL,
    preco          NUMERIC(10, 2) NOT NULL,
    criado_em      TIMESTAMP NOT NULL DEFAULT now()
);
-- Índice funcional único: lookup de find-or-create por nome normalizado (trim + case-insensitive).
CREATE UNIQUE INDEX uq_produto_nome_normalizado ON produto (LOWER(TRIM(nome)));

CREATE TABLE pedido (
    codigo_pedido  INT PRIMARY KEY,
    codigo_cliente INT NOT NULL,
    criado_em      TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX ix_pedido_cliente ON pedido (codigo_cliente);

CREATE TABLE item_pedido (
    codigo_pedido  INT NOT NULL REFERENCES pedido (codigo_pedido),
    codigo_produto INT NOT NULL REFERENCES produto (codigo_produto),
    codigo_cliente INT NOT NULL,
    preco          NUMERIC(10, 2) NOT NULL,
    quantidade     INT NOT NULL,
    PRIMARY KEY (codigo_pedido, codigo_produto),
    CONSTRAINT ck_item_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_preco CHECK (preco >= 0)
);
